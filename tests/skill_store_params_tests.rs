//! kkclaw SkillStore 复现测试
//!
//! 背景：kkclaw 的 SkillStore 使用 execute_params 向有 FTS 索引的 skills 表
//! 插入 Skill 数据。部分 Skill（prompts 含换行/管道符/代码块）失败。
//!
//! 运行：
//!   cargo test --test skill_store_params_tests -- --nocapture

use kkdb::types::Value;
use kkdb::vm::execute::{ExecResult, VM};

/// kkclaw skills 表的真实 DDL（完全一致）
fn create_skills_table(vm: &mut VM) {
    vm.execute_sql(
        "CREATE TABLE IF NOT EXISTS skills \
         (name TEXT PRIMARY KEY, desc TEXT, tags TEXT, prompts TEXT, embedding BLOB)",
    )
    .unwrap();

    vm.execute_sql(
        "CREATE FULLTEXT INDEX IF NOT EXISTS idx_skills_ft \
         ON skills (desc, tags, prompts)",
    )
    .unwrap();
}

// ─── Case 1: 基本 INSERT OR REPLACE（简单内容）────────────────────────────────

/// 验证 execute_params 能向有 FTS 索引的表写入简单 TEXT 值
#[test]
fn test_params_insert_simple_with_fts() {
    let mut vm = VM::new_memory();
    create_skills_table(&mut vm);

    let r = vm.execute_params(
        "INSERT OR REPLACE INTO skills (name, desc, tags, prompts) VALUES (?, ?, ?, ?)",
        &[
            Value::Text("langchain".into()),
            Value::Text("LangChain AI framework for building LLM apps".into()),
            Value::Text("llm agent python framework".into()),
            Value::Text("Use LangChain to build powerful AI pipelines.".into()),
        ],
    );
    assert!(r.is_ok(), "Simple INSERT with FTS failed: {r:?}");

    if let ExecResult::QueryResult { rows, .. } = vm.execute_sql("SELECT name FROM skills").unwrap()
    {
        assert_eq!(rows.len(), 1, "Expected 1 row");
    }
}

